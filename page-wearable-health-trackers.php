// Accordion Toggle for Case Studies
document.addEventListener('DOMContentLoaded', () => {
    const accordionContainer = document.getElementById('wearables-case-studies-accordion');
    if (accordionContainer) {
        const accordionItems = accordionContainer.querySelectorAll('.accordion-item');
        accordionItems.forEach(item => {
            const header = item.querySelector('.accordion-header');
            const content = item.querySelector('.accordion-content');
            const icon = header.querySelector('.accordion-icon');
            if (header && content && icon) {
                header.addEventListener('click', () => {
                    header.setAttribute('aria-expanded', !(header.getAttribute('aria-expanded') === 'true'));
                    content.classList.toggle('hidden');
                    icon.classList.toggle('rotate-180');
                });
            }
        });
    }
});
document.addEventListener('DOMContentLoaded', () => {
    // Accordion Logic
    const accordionContainer = document.getElementById('wearables-case-studies-accordion-v2');
    if (accordionContainer) {
        const accordionItems = accordionContainer.querySelectorAll('.accordion-item');
        accordionItems.forEach(item => {
            const header = item.querySelector('.accordion-header');
            const content = item.querySelector('.accordion-content');
            const icon = header.querySelector('.accordion-icon');
            if (header && content && icon) {
                header.addEventListener('click', () => {
                    header.setAttribute('aria-expanded', !(header.getAttribute('aria-expanded') === 'true'));
                    content.classList.toggle('hidden');
                    icon.classList.toggle('rotate-180');
                });
            }
        });
    }

    // Tabs Logic
    const tabContainer = document.getElementById('solution-tabs');
    if (tabContainer) {
        const tabs = tabContainer.querySelectorAll('.tab-button');
        const panels = document.querySelectorAll('.tab-panel');

        tabs.forEach((tab, index) => {
            tab.addEventListener('click', () => {
                // Deactivate all tabs and panels
                tabs.forEach(t => {
                    t.setAttribute('aria-current', 'false');
                    t.classList.remove('border-brand-secondary', 'text-brand-primary');
                    t.classList.add('border-transparent', 'text-slate-500', 'hover:text-slate-700', 'hover:border-slate-400');
                });
                panels.forEach(p => p.classList.add('hidden'));

                // Activate the clicked tab and its panel
                tab.setAttribute('aria-current', 'true');
                tab.classList.add('border-brand-secondary', 'text-brand-primary');
                tab.classList.remove('border-transparent', 'text-slate-500', 'hover:text-slate-700', 'hover:border-slate-400');
                if(index === 0) document.getElementById('tab-panel-features').classList.remove('hidden');
                if(index === 1) document.getElementById('tab-panel-integrations').classList.remove('hidden');
                if(index === 2) document.getElementById('tab-panel-applications').classList.remove('hidden');
            });
        });
    }
});
